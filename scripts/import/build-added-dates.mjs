// One-off, reproducible: derives `added_at` for each car from git history (audit finding D13).
//
// A model's date = the commit date where it first appears in the car data file, with two rules:
//  - Initial cataloguing: everything that appeared on the repo's FIRST day is left undated (NULL).
//    That date says when the site was built, not when the model joined the collection.
//  - Id renames (typo fixes like "altara" → "altaya", color changes) keep the ORIGINAL date: a removed
//    and an added entry with the same name + year + manufacturer in one commit are the same model.
//
//   node scripts/import/build-added-dates.mjs   → writes scripts/import/added-dates.json
import {execFileSync} from "node:child_process";
import {writeFileSync} from "node:fs";

const FILE = "src/data/car-models.json";
const git = (...args) => execFileSync("git", args, {encoding: "utf8", maxBuffer: 64 * 1024 * 1024});

// --follow tracks renames of the data file, --name-only gives its path *in that commit*.
// (--reverse is broken together with --follow, so reverse in JS to walk oldest → newest.)
const commits = git("log", "--follow", "--name-only", "--format=@@%H %ad", "--date=short", "--", FILE)
    .split("@@").filter(Boolean).reverse().map((chunk) => {
        const [header, ...files] = chunk.trim().split("\n");
        const [hash, date] = header.split(" ");
        return {hash, date, path: files.find(Boolean)?.trim() ?? FILE};
    });

const identity = (m) => `${m.name}|${m.year}|${m.manufacturer}`;
const firstDay = commits[0].date;
const dateOf = new Map(); // id → date | null
let previous = new Map(); // id → model, from the previous commit
const renames = [];

for (const {hash, date, path} of commits) {
    let models;
    try {
        models = JSON.parse(git("show", `${hash}:${path}`));
    } catch {
        continue; // file deleted or unparsable in this commit
    }
    const current = new Map(models.map((m) => [m.id, m]));
    const removed = [...previous.values()].filter((m) => !current.has(m.id));
    const added = [...current.values()].filter((m) => !dateOf.has(m.id));

    // Pass 1: same name + year + manufacturer. Pass 2 (name also fixed, e.g. "Corvetter" → "Corvette"):
    // exactly one removed and one added entry share year + manufacturer in this commit.
    const loose = (m) => `${m.year}|${m.manufacturer}`;
    const matched = new Map(); // newId → oldId
    for (const m of added) {
        const old = removed.find((r) => identity(r) === identity(m));
        if (old) matched.set(m.id, old.id);
    }
    const oldUsed = new Set(matched.values());
    for (const m of added.filter((a) => !matched.has(a.id))) {
        const newCandidates = added.filter((a) => !matched.has(a.id) && loose(a) === loose(m));
        const oldCandidates = removed.filter((r) => !oldUsed.has(r.id) && loose(r) === loose(m));
        if (newCandidates.length === 1 && oldCandidates.length === 1) {
            matched.set(m.id, oldCandidates[0].id);
            oldUsed.add(oldCandidates[0].id);
        }
    }

    for (const m of added) {
        const oldId = matched.get(m.id);
        if (oldId !== undefined && dateOf.has(oldId)) {
            dateOf.set(m.id, dateOf.get(oldId));
            renames.push({from: oldId, to: m.id, commit: hash.slice(0, 7)});
        } else {
            dateOf.set(m.id, date === firstDay ? null : date);
        }
    }
    previous = current;
}

const current = JSON.parse(git("show", `HEAD:${FILE}`)).map((m) => m.id);
const dates = Object.fromEntries(current.sort().map((id) => [id, dateOf.get(id) ?? null]));
const dated = Object.values(dates).filter(Boolean).length;

writeFileSync(
    new URL("./added-dates.json", import.meta.url),
    JSON.stringify({
        _comment: `Generated by build-added-dates.mjs. null = catalogued on the repo's first day (${firstDay}); real date unknown.`,
        _renamesFollowed: renames,
        dates,
    }, null, 2) + "\n",
);
console.log(`${current.length} models · ${dated} dated from git · ${current.length - dated} undated (first day ${firstDay}) · ${renames.length} id renames followed`);
